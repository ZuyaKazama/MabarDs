#!/usr/bin/env python3
"""Cross-compile the melonDS OpenGL renderer shaders (desktop GLSL 1.40) to GLSL ES 3.20.

Desktop GLSL allows implicit int->float conversions that GLSL ES rejects, so a textual
rewrite is not enough. Each shader is compiled to SPIR-V with glslang (as GLSL 4.50, which
accepts the same implicit conversions) and decompiled to ESSL 3.20 with SPIRV-Cross.

The result is written to app/src/main/cpp/gles/gles_shaders.inc as a table keyed by a
FNV-1a hash of the exact source string melonDS passes at runtime, so the Android build
itself needs no extra tools. Re-run this after updating melonDS.

Requires: glslangValidator, spirv-cross (apt install glslang-tools spirv-cross)
Usage:    scripts/gen_gles_shaders.py [path/to/melonDS]
"""
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MELONDS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "app/src/main/cpp/external/melonDS")
SHADERS = os.path.join(MELONDS, "src/OpenGL_shaders")
OUT = os.path.join(ROOT, "app/src/main/cpp/gles/gles_shaders.inc")

# Sources melonDS builds at runtime by inserting a line after "#version"
VARIANTS = {
    "3DRenderVS.glsl": ["", "#define WBuffer\n"],
    "3DRenderFS.glsl": ["", "#define WBuffer\n"],
}

PRECISION = """precision highp float;
precision highp int;
precision highp sampler2D;
precision highp sampler2DArray;
precision highp sampler3D;
precision highp usampler2D;
precision highp usampler2DArray;
precision highp isampler2D;
precision highp samplerBuffer;
precision highp usamplerBuffer;
precision highp isamplerBuffer;
"""


def fnv1a64(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def strip_layout(m):
    # drop auto-assigned locations/bindings: melonDS binds attributes, outputs,
    # samplers and uniform blocks itself by name.
    items = [i.strip() for i in m.group(1).split(",")]
    items = [i for i in items if not re.match(r"(location|binding)\s*=", i)]
    return "layout(%s) " % ", ".join(items) if items else ""


def cross_compile(src: str, stage: str, tmp: str) -> str:
    desktop = re.sub(r"#version\s+\d+[^\n]*", "#version 450 core", src, count=1)
    inp = os.path.join(tmp, "in." + stage)
    spv = os.path.join(tmp, "out.spv")
    with open(inp, "w") as f:
        f.write(desktop)
    subprocess.run(["glslangValidator", "-G", "--auto-map-locations", "--auto-map-bindings",
                    "-g", "-S", stage, "-o", spv, inp], check=True, stdout=subprocess.PIPE)
    es = subprocess.run(["spirv-cross", "--es", "--version", "320", spv],
                        check=True, stdout=subprocess.PIPE, text=True).stdout
    # SPIRV-Cross defaults fragment shaders to mediump; DS depth/colour maths needs highp
    es = re.sub(r"precision\s+mediump\s+", "precision highp ", es)
    es = re.sub(r"layout\(([^)]*)\)\s*", strip_layout, es)
    # put our sampler precision defaults right after the version line
    es = es.replace("#version 320 es\n", "#version 320 es\n" + PRECISION, 1)
    return es


def main():
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        for name in sorted(os.listdir(SHADERS)):
            if not name.endswith(".glsl"):
                continue
            stage = "frag" if name.endswith("FS.glsl") else "vert"
            with open(os.path.join(SHADERS, name), newline="") as f:
                base = f.read()
            for extra in VARIANTS.get(name, [""]):
                src = base
                if extra:
                    pos = src.find("\n") + 1
                    src = src[:pos] + extra + src[pos:]
                es = cross_compile(src, stage, tmp)
                entries.append((fnv1a64(src.encode()), name + (" +" + extra.strip() if extra else ""), es))
                print("ok", name, extra.strip())

    with open(OUT, "w") as f:
        f.write("// Generated by scripts/gen_gles_shaders.py - do not edit.\n")
        f.write("// melonDS OpenGL renderer shaders cross-compiled to GLSL ES 3.20.\n")
        f.write("static const struct { unsigned long long Hash; const char* Name; const char* Source; } kGlesShaders[] = {\n")
        for h, name, es in entries:
            assert ")EMUNDS\"" not in es
            f.write('    {0x%016xULL, "%s", R"EMUNDS(%s)EMUNDS"},\n' % (h, name, es))
        f.write("};\n")
    print("wrote", OUT, len(entries), "shaders")


if __name__ == "__main__":
    main()
